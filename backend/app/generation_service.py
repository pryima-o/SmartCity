from google import genai
from google.genai import types

from app.search_service import retrieve_relevant_chunks


# ============================================================
# GEMINI CLIENT
# ============================================================

client = genai.Client(
    http_options={"api_version": "v1"}
)


MODELS = [
    "gemini-3.1-flash-lite",
]


# ============================================================
# SYSTEM INSTRUCTION
# ============================================================

SYSTEM_INSTRUCTION = """
Ты — AI-ассистент муниципалитета Кишинева.

Твоя задача — отвечать гражданам ТОЛЬКО на основании
предоставленного КОНТЕКСТА из официальных документов.

СТРОГИЕ ПРАВИЛА:

1. ЯЗЫК ОТВЕТА.

В промпте будет явно указано:
ЯЗЫК ОТВЕТА: ROMÂNĂ
или
ЯЗЫК ОТВЕТА: РУССКИЙ

Ты ОБЯЗАН отвечать только на указанном языке.

Если указано ROMÂNĂ:
- весь ответ должен быть на румынском;
- не используй русский язык;
- не переводи ответ на русский;
- не смешивай русский и румынский.

Если указано РУССКИЙ:
- весь ответ должен быть на русском;
- не используй румынский язык;
- не смешивай русский и румынский.

2. Используй ТОЛЬКО информацию из КОНТЕКСТА.

3. НЕ используй свои знания о Кишинёве
или любые другие внешние знания.

4. Если КОНТЕКСТ не содержит ответа на вопрос,
не выдумывай ответ.

В этом случае сообщи на указанном языке:

Русский:
"Данной информации нет в официальных документах."

Румынский:
"Informația solicitată nu se regăsește în documentele oficiale."

5. Если КОНТЕКСТ содержит только частично относящуюся
информацию, сначала сообщи, что конкретный ответ
не найден, а затем кратко укажи связанную информацию,
которая действительно присутствует.

6. Каждое существенное утверждение сопровождай источником
в формате:

[regulament.txt, Пассаж 27]

7. Используй только реальные document и passage,
которые присутствуют в КОНТЕКСТЕ.

8. Никогда не выдумывай:
- документы;
- пассажи;
- даты;
- адреса;
- суммы;
- правила;
- URL.

9. Отвечай кратко и непосредственно.

10. Не повторяй вопрос пользователя.

11. Не используй Markdown-ссылки.

12. Не добавляй отдельный список источников в конце.
Источник должен находиться непосредственно рядом
с соответствующим утверждением.
"""


# ============================================================
# LANGUAGE DETECTION
# ============================================================

def detect_question_language(user_question: str) -> str:
    """
    Определяет язык пользовательского вопроса.

    Для MVP:
    - кириллица -> русский
    - латиница -> румынский

    Румынский язык в данном проекте использует латиницу,
    поэтому для текущего сценария этого достаточно.
    """

    has_cyrillic = any(
        "\u0400" <= char <= "\u04FF"
        for char in user_question
    )

    if has_cyrillic:
        return "РУССКИЙ"

    return "ROMÂNĂ"


# ============================================================
# ANSWER
# ============================================================

def answer_citizen_question(user_question: str) -> str:

    # ========================================================
    # 1. DETECT LANGUAGE
    # ========================================================

    answer_language = detect_question_language(
        user_question
    )

    # ========================================================
    # 2. RAG SEARCH
    # ========================================================

    context_chunks = retrieve_relevant_chunks(
        user_query=user_question,
        limit=3
    )

    if not context_chunks:

        if answer_language == "ROMÂNĂ":
            return (
                "Informația solicitată nu se regăsește "
                "în documentele oficiale."
            )

        return (
            "Данной информации нет "
            "в официальных документах."
        )

    # ========================================================
    # 3. FORMAT CONTEXT
    # ========================================================

    formatted_context = []

    for chunk in context_chunks:

        formatted_context.append(
            f"""
[DOCUMENT: {chunk['source_file']}]
[PASSAGE: {chunk['passage_id']}]
[SIMILARITY: {chunk['similarity']:.3f}]

{chunk['text']}
"""
        )

    context = "\n".join(formatted_context)

    # ========================================================
    # 4. PROMPT
    # ========================================================

    prompt = f"""
ЯЗЫК ОТВЕТА: {answer_language}

ОБЯЗАТЕЛЬНО:
Ответ должен быть полностью написан на языке,
указанном выше.

КОНТЕКСТ ИЗ ОФИЦИАЛЬНЫХ ДОКУМЕНТОВ:

{context}

ВОПРОС ГРАЖДАНИНА:

{user_question}

Сформируй краткий ответ строго на основании КОНТЕКСТА.

Не используй информацию, которой нет в КОНТЕКСТЕ.

Каждое существенное утверждение должно иметь источник
в формате:

[document, Пассаж X]
"""

    # ========================================================
    # 5. GENERATION
    # ========================================================

    for model_name in MODELS:

        try:

            response = client.models.generate_content(
                model=model_name,
                contents=prompt,
                config=types.GenerateContentConfig(
                    system_instruction=SYSTEM_INSTRUCTION,
                    max_output_tokens=500,
                    temperature=0.1,
                ),
            )

            answer = response.text

            if answer and answer.strip():

                return answer.strip()

        except Exception as e:

            print(
                f"Gemini {model_name} failed: {e}"
            )

            continue

    # ========================================================
    # 6. FALLBACK
    # ========================================================

    if answer_language == "ROMÂNĂ":

        return (
            "Serviciul AI este temporar indisponibil. "
            "Vă rugăm să încercați din nou peste câteva secunde."
        )

    return (
        "Сервис AI временно недоступен. "
        "Пожалуйста, повторите запрос через несколько секунд."
    )